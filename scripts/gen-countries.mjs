// Regenerates src/core/data/countries.ts from the `world-countries` dataset.
// Run: npm run gen:countries
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const raw = require("world-countries/countries.json");

/** world-countries `region`/`subregion` -> our 7-continent model */
function continentOf(c) {
  if (c.region === "Antarctic" || c.region === "") return "Antarctica";
  if (c.region === "Americas") {
    return c.subregion === "South America" ? "South America" : "North America";
  }
  return c.region; // Africa | Asia | Europe | Oceania
}

const rows = raw
  .filter((c) => c.ccn3 && c.cca2 && c.cca3)
  .map((c) => ({
    numeric: Number(c.ccn3),
    iso2: c.cca2,
    iso3: c.cca3,
    name: c.name.common,
    continent: continentOf(c),
  }))
  .sort((a, b) => a.name.localeCompare(b.name));

// The UN has 193 member states; pin the denominator to that regardless of any
// quirk in the source dataset's `unMember` flags.
const UN_MEMBER_COUNT = 193;

const lines = rows
  .map(
    (r) =>
      `  { numeric: ${r.numeric}, iso2: ${JSON.stringify(r.iso2)}, iso3: ${JSON.stringify(
        r.iso3,
      )}, name: ${JSON.stringify(r.name)}, continent: ${JSON.stringify(r.continent)} },`,
  )
  .join("\n");

const out = `/**
 * ISO 3166-1: numeric <-> alpha-2 <-> alpha-3 + name + continent.
 *
 * GENERATED by scripts/gen-countries.mjs from the \`world-countries\` dataset —
 * do not edit by hand. Run \`npm run gen:countries\` to refresh.
 *
 * \`iso2\` matches what the Nominatim geocoder returns (\`address.country_code\`);
 * the rest of the app stores \`iso3\` on entries. \`numeric\` matches the ids in
 * world-atlas \`countries-110m\` used by the map.
 */

export type Continent =
  | "Africa"
  | "Asia"
  | "Europe"
  | "North America"
  | "South America"
  | "Oceania"
  | "Antarctica";

export const CONTINENTS: Continent[] = [
  "Europe",
  "Asia",
  "Africa",
  "North America",
  "South America",
  "Oceania",
  "Antarctica",
];

export interface CountryRow {
  numeric: number;
  iso2: string;
  iso3: string;
  name: string;
  continent: Continent;
}

export const COUNTRIES: CountryRow[] = [
${lines}
];

export const UN_MEMBER_COUNT = ${UN_MEMBER_COUNT};

const _byISO3 = new Map(COUNTRIES.map((c) => [c.iso3, c]));
const _byISO2 = new Map(COUNTRIES.map((c) => [c.iso2, c]));
const _byNumeric = new Map(COUNTRIES.map((c) => [String(c.numeric).padStart(3, "0"), c]));

export const countryByISO3 = (iso3: string): CountryRow | undefined =>
  _byISO3.get(iso3.toUpperCase());
export const countryByISO2 = (iso2: string): CountryRow | undefined =>
  _byISO2.get(iso2.toUpperCase());
export const countryByNumeric = (n: string | number): CountryRow | undefined =>
  _byNumeric.get(String(n).padStart(3, "0"));

/** Continent -> count of UN members (approx; from the generated table). */
export const CONTINENT_TOTALS: Record<Continent, number> = COUNTRIES.reduce(
  (acc, c) => {
    acc[c.continent] = (acc[c.continent] ?? 0) + 1;
    return acc;
  },
  {} as Record<Continent, number>,
);
`;

const target = fileURLToPath(new URL("../src/core/data/countries.ts", import.meta.url));
writeFileSync(target, out);
console.log(`Wrote ${rows.length} countries to ${target}`);
